import { Chord, Note } from "tonal";
import { highestPitch, isBlackKey } from "@/lib/midi/song";

/** Chord tones climbing from the root, each lifted an octave until it clears the
 * one below, so the root stays the bass and the arpeggio reads in root position. */
export function chordMidi(symbol: string, octave: number): number[] {
  const raw = Chord.get(symbol)
    .notes.map((name) => Note.midi(`${name}${octave}`))
    .filter((value): value is number => value !== null);
  const ascending: number[] = [];
  for (const pitch of raw) {
    let lifted = pitch;
    const previous = ascending[ascending.length - 1];
    while (previous !== undefined && lifted <= previous) {
      lifted += 12;
    }
    ascending.push(lifted);
  }
  return ascending;
}

