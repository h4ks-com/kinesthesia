export function whiteKeyFrom(base: number, steps: number): number {
  let pitch = base;
  while (isBlackKey(pitch) && pitch < highestPitch) {
    pitch += 1;
  }
  for (let moved = 0; moved < steps && pitch < highestPitch; moved += 1) {
    pitch += 1;
    while (isBlackKey(pitch) && pitch < highestPitch) {
      pitch += 1;
    }
  }
  return pitch;
}
